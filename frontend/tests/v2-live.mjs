import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { chromium } from 'playwright-core';

const browserName = process.env.V2_BROWSER || 'chrome';
const executablePath = browserName === 'edge' ? 'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe' : 'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe';
const out = '../docs/evidence/v2-mvp';
await mkdir(out, { recursive: true });
const browser = await chromium.launch({ executablePath, headless: true, args: ['--no-sandbox', '--enable-unsafe-swiftshader'] });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, locale: 'zh-CN' });
const page = await context.newPage();
const errors = [];
page.on('pageerror', (error) => errors.push(error.message.replace(/https?:\/\/\S+/g, '[URL]')));
let interpretCalls = 0;
let routeCalls = 0;
let routeData;
let analysisData;
page.on('request', (request) => {
  if (request.url().endsWith('/api/v2/interpret')) interpretCalls++;
  if (request.url().endsWith('/api/v2/route')) routeCalls++;
});
page.on('response', async (response) => {
  if (response.url().endsWith('/api/v2/route') && response.ok()) routeData = await response.json();
  if (response.url().endsWith('/api/v2/interpret') && response.ok()) analysisData = await response.json();
});
const text = '我想从天津大学卫津路校区去天津医科大学总医院。';
const results = { browser: browserName, recorded_on: '2026-10-08', evidence_type: 'AUTOMATED_EVIDENCE', phases: {}, errors };
try {
  await page.goto('http://127.0.0.1:5173/', { waitUntil: 'domcontentloaded' });
  await page.getByText('服务已连接', { exact: true }).waitFor({ timeout: 15000 });
  await page.waitForFunction(() => document.querySelectorAll('.amap-maps').length === 1, { timeout: 30000 });
  await page.getByRole('button', { name: '3D 城市', exact: true }).waitFor();
  assert.equal(await page.locator('.amap-logo').count() > 0, true);
  const layout = await page.evaluate(() => ({ input: document.querySelector('.v2-input-panel').getBoundingClientRect().height, map: document.querySelector('.v2-map').getBoundingClientRect().height }));
  await page.screenshot({ path: `${out}/${browserName}-01-initial.png` });
  results.phases.layout = { status: 'PASS', layout, attribution: true };
  await page.getByLabel('出行需求', { exact: true }).fill(text);
  assert.equal(interpretCalls, 0, 'typing must not analyze');
  await page.getByRole('button', { name: '完成', exact: true }).click();
  await page.getByRole('heading', { name: '路线方案', exact: true }).waitFor({ timeout: 65000 });
  await page.getByText('已显示高德真实驾车道路参考。', { exact: true }).waitFor({ timeout: 15000 });
  await page.getByRole('heading', { name: '地面行程时间', exact: true }).waitFor();
  await page.getByRole('list', { name: '地面出发与到达安排' }).waitFor();
  results.phases.time_plan = { status: 'PASS', visible: true, default: '现在出发', no_operational_air_time: true };
  assert.equal(interpretCalls, 1); assert.equal(routeCalls, 1);
  assert.equal(routeData.ground.geometry.length > 10, true);
  assert.equal(routeData.origin.name, '天津大学卫津路校区');
  assert.equal(routeData.destination.name, '天津医科大学总医院');
  results.phases.analysis = { status: 'PASS', source: analysisData.source, intent: analysisData.intent };
  results.phases.ground = { status: 'PASS', source: routeData.ground.source, points: routeData.ground.geometry.length, distance_m: routeData.ground.distance_m, duration_min: routeData.ground.duration_min, retrieved_at: routeData.ground.retrieved_at };
  const sampleIndices = [0, Math.floor(routeData.ground.geometry.length/2), routeData.ground.geometry.length-1];
  const conversion = await context.request.post('http://127.0.0.1:5173/__amap_convert', { data: { points: sampleIndices.map((i) => routeData.ground_wgs84[i]) } });
  const converted = await conversion.json();
  assert.equal(conversion.ok() && converted.available, true, 'official coordinate control unavailable');
  const deviations = converted.points.map(([lon, lat], index) => {
    const target = routeData.ground.geometry[sampleIndices[index]];
    return Math.hypot((lon-target[0])*111320*Math.cos(lat*Math.PI/180), (lat-target[1])*110540);
  });
  assert.equal(Math.max(...deviations) < 5, true, 'WGS84/GCJ-02 alignment must be within 5m of Amap official conversion');
  results.phases.coordinate_alignment = { status: 'PASS', control: 'AMap official gps to GCJ-02 conversion', sample_count: 3, max_deviation_m: Math.max(...deviations), scope: 'three actual Tianjin route points; not survey certification' };
  await page.screenshot({ path: `${out}/${browserName}-02-ground.png` });
  await page.getByRole('button', { name: /模拟空中路线 空间参考/ }).click();
  await page.getByText('模拟空中路线 · 紫色虚线，仅作空间参考。', { exact: true }).waitFor();
  assert.equal(routeCalls, 1, 'view selection must reuse the same route');
  await page.screenshot({ path: `${out}/${browserName}-03-air.png` });
  results.phases.air = { status: 'PASS', data_status: routeData.air.data_status, points: routeData.air.geometry.length, max_visual_height_m: Math.max(...routeData.air.geometry.map((p) => p[2])) };
  const streetLoaded = page.waitForResponse((r) => /tile\.openstreetmap\.org\/1[4-9]\//.test(r.url()) && r.ok(), { timeout: 30000 });
  await page.getByRole('button', { name: '3D 城市', exact: true }).click();
  await page.locator('.v2-cesium canvas').waitFor({ timeout: 30000 });
  const buildingsResponse = await page.waitForResponse((r) => r.url().includes('/api/v2/buildings?'), { timeout: 30000 }).catch(() => null);
  let buildingData = buildingsResponse?.ok() ? await buildingsResponse.json() : null;
  await streetLoaded;
  await page.waitForTimeout(2000);
  await page.screenshot({ path: `${out}/${browserName}-04-3d.png` });
  const model = await context.request.get('http://127.0.0.1:5173/models/reference-aircraft.gltf');
  assert.equal(model.ok(), true);
  results.phases.scene = { status: buildingData?.features.length ? 'PASS' : 'PARTIAL', street_tiles: 'actual HTTP 200 at zoom >=14', buildings: buildingData?.features.length ?? 0, scene_canvas: true, aircraft_asset_loaded: true, notice: await page.locator('.v2-scene-info').innerText() };
  const oldCanvas = await page.locator('.v2-cesium canvas').elementHandle();
  // Inspect the single current acceptance viewport; never scan/prefetch OSM tiles.
  await page.getByRole('button', { name: '二维地图', exact: true }).click();
  await page.getByRole('button', { name: '3D 城市', exact: true }).click();
  assert.equal(await oldCanvas.evaluate((node) => node.isConnected), true);
  assert.equal(await page.locator('.v2-cesium canvas').count(), 1);
  assert.equal(interpretCalls, 1); assert.equal(routeCalls, 1);
  await page.getByRole('button', { name: '修改行程', exact: true }).click();
  assert.equal(await page.getByLabel('出行需求', { exact: true }).inputValue(), text);
  await page.getByLabel('出行需求', { exact: true }).fill('从天津大学去总医院。');
  await page.getByRole('button', { name: '完成', exact: true }).click();
  await page.getByRole('heading', { name: '确认具体地点', exact: true }).waitFor({ timeout: 65000 });
  assert.equal(routeCalls, 1, 'ambiguous input must not route silently');
  await page.getByRole('region', { name: '选择出发地', exact: true }).getByRole('button', { name: /^天津大学卫津路校区 / }).click();
  assert.equal(routeCalls, 1, 'one ambiguous endpoint still missing must not route');
  await page.screenshot({ path: `${out}/${browserName}-05-ambiguity.png` });
  await page.getByRole('region', { name: '选择目的地', exact: true }).getByRole('button', { name: /^天津医科大学总医院 / }).click();
  await page.getByRole('heading', { name: '路线方案', exact: true }).waitFor({ timeout: 35000 });
  results.phases.ambiguity = { status: 'PASS', explicit_selection: true, auto_route_when_both_selected: true, no_extra_confirmation: true };
  await page.getByRole('button', { name: '修改行程', exact: true }).click();
  await page.route('**/api/v2/interpret', (r) => r.fulfill({ status: 502, contentType: 'application/json', body: JSON.stringify({ detail: 'DeepSeek 分析超时，请稍后点击完成重试。文字已保留。' }) }));
  await page.getByRole('button', { name: '完成', exact: true }).click();
  await page.getByRole('alert').waitFor();
  assert.equal(await page.getByLabel('出行需求', { exact: true }).inputValue(), '从天津大学去总医院。');
  assert.equal(await page.getByRole('heading', { name: '路线方案', exact: true }).count(), 0);
  await page.screenshot({ path: `${out}/${browserName}-06-error.png` });
  results.phases.error = { status: 'PASS', injected_failure: true, text_preserved: true, old_route_cleared: true };
  assert.deepEqual(errors, []);
  await writeFile(`${out}/${browserName}-results.json`, JSON.stringify(results, null, 2));
  console.log(JSON.stringify(results, null, 2));
} catch (error) {
  await page.screenshot({ path: `${out}/${browserName}-failure.png` });
  console.log('Visible UI:', (await page.locator('body').innerText()).slice(0, 4000));
  throw error;
} finally { await browser.close(); }
